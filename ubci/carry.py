"""Refresh config/carry.yaml: for every pinned component, the patches it
carries on top of its upstream (distance to upstream), with review links.

python3 -m ubci.carry [--check]

Clones live in $UBCI_WORK/src/carry-<repo>. --check exits 1 when the
checked-in file does not match the pins (CI runs it)."""
import os
import sys

import yaml

from fwci import carry as fcarry

from . import config
from .fetch import WORK

OUT = os.path.join(config.CONFIG, "carry.yaml")


def clone(url, upstream_url, upstream_branch, commit):
    d = os.path.join(WORK, "src", "carry-" + url.rstrip("/").split("/")[-1])
    if not os.path.isdir(d):
        os.makedirs(os.path.dirname(d), exist_ok=True)
        fcarry.subprocess.run(["git", "clone", "-q", "--bare", url, d], check=True)
    fcarry.git(d, "fetch", "-q", url, commit)
    fcarry.git(d, "fetch", "-q", upstream_url, "+%s:refs/upstream/%s" % (upstream_branch, upstream_branch))
    return d


def component(pin):
    up = pin["upstream"]
    d = clone(pin["repo"], up["repo"], up["branch"], pin["commit"])
    resolve = (lambda cid: fcarry.resolve_gerrit(up["gerrit"], up["project"], cid)) \
        if up.get("gerrit") else None
    c = fcarry.carried(d, "refs/upstream/" + up["branch"], pin["commit"], resolve=resolve)
    return {"repo": up["repo"], "base": c["base"], "distance": c["distance"],
            "carried": c["carried"], "pin": pin["commit"]}


def generate():
    out = {}
    for board, pins in sorted(config.pins().items()):
        # A pending pin's commit cannot be fetched: no distance yet.
        out[board] = {name: component(pin) for name, pin in sorted(pins.items())
                      if isinstance(pin, dict) and "upstream" in pin and not pin.get("pending")}
    return out


if __name__ == "__main__":
    new = generate()
    if "--check" in sys.argv:
        old = yaml.safe_load(open(OUT)) if os.path.exists(OUT) else None
        stale = [(b, c) for b in new for c in new[b]
                 if (old or {}).get(b, {}).get(c, {}).get("pin") != new[b][c]["pin"]
                 or old[b][c]["distance"] != new[b][c]["distance"]]
        if stale:
            raise SystemExit("config/carry.yaml is stale for %s; run python3 -m ubci.carry" % stale)
        print("carry.yaml matches the pins")
    else:
        with open(OUT, "w") as f:
            f.write("# Generated by python3 -m ubci.carry from config/pins.yaml: the patches\n"
                    "# each pinned component carries on top of its upstream.\n")
            yaml.safe_dump(new, f, sort_keys=True, width=1000)
        print(OUT)
